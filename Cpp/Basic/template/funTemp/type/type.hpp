/**
 * @file type.hpp
 * @brief This is a header file that defines type aliases for various fundamental data types in C++. It provides a convenient way to refer to these types using shorter names.
 * @author Radheshyam
 * @date 19-Oct-2026
 */
#ifndef __TYPE_HPP__
#define __TYPE_HPP__
typedef float float_t;
typedef double double_t;
typedef int int_t;
typedef short short_t;
typedef unsigned int uint_t;
typedef unsigned short ushort_t;
typedef long long_t;
typedef unsigned long ulong_t;
typedef long long llong_t;
typedef unsigned long long ullong_t;
#endif /*__TYPE_HPP__*/